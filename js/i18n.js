let LANG = 'ru';

function detectLang() {
  const l = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  return /^(ru|uk|be|kk)/i.test(l) ? 'ru' : 'en';
}

function setLang(l) {
  LANG = l === 'en' ? 'en' : 'ru';
  document.documentElement.lang = LANG;
  document.title = t('title');
}

